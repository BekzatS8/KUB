-- Лид у сделки теперь ОПЦИОНАЛЕН: клиент «с улицы» (без переписки/лида) —
-- сделку всё равно нужно завести (обратная связь заказчика 21.07.2026).
-- Раньше deals.lead_id был NOT NULL (001_init), из-за чего сделка без лида не
-- создавалась. Снимаем NOT NULL. ALTER ... DROP NOT NULL идемпотентен.
-- Уникальный индекс deals_lead_unique_idx на lead_id остаётся: в Postgres
-- несколько NULL в UNIQUE-индексе разрешены, поэтому несколько сделок «без
-- лида» не конфликтуют, а «один лид — одна сделка» сохраняется.
BEGIN;

ALTER TABLE IF EXISTS deals ALTER COLUMN lead_id DROP NOT NULL;

COMMIT;
