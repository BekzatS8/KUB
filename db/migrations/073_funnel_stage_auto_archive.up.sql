-- Настраиваемый авто-архив этапа воронки. Когда карточка (сделка/лид)
-- переходит на этап с auto_archive = TRUE, она автоматически уходит в архив
-- («когда всё уже выполнится» — обратная связь заказчика 17.07.2026).
-- Миграции переигрываются на каждом деплое — держим идемпотентно и НЕ
-- бэкфиллим значения, чтобы не воскрешать ручные правки администратора.
BEGIN;

ALTER TABLE IF EXISTS funnel_stages
    ADD COLUMN IF NOT EXISTS auto_archive BOOLEAN NOT NULL DEFAULT FALSE;

COMMIT;
